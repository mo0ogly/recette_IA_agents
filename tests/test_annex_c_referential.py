"""Drift guard for the Annex C governed-action referential.

corpus/referentials/annex-c-governed-actions.json is generated by
scripts/gen_annex_c_referential.py from the committed catalog. This test asserts
the committed file is exactly what the generator produces today (regenerate +
compare) and that every row stays consistent with the catalog. Editing the
catalog without regenerating, or hand-editing the JSON, turns this red (R20).

Run the generator to refresh: python -m scripts.gen_annex_c_referential
"""

from __future__ import annotations

import importlib.util
import json
import unittest
from collections import Counter
from pathlib import Path

from recette.platform.catalog import load_catalog

_REPO_ROOT = Path(__file__).resolve().parent.parent
_REFERENTIAL = _REPO_ROOT / "corpus" / "referentials" / "annex-c-governed-actions.json"


def _load_generator():
    """Import scripts/gen_annex_c_referential.py by path (scripts/ is not a package)."""
    spec = importlib.util.spec_from_file_location(
        "gen_annex_c_referential", _REPO_ROOT / "scripts" / "gen_annex_c_referential.py"
    )
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


class TestAnnexCReferential(unittest.TestCase):
    def setUp(self) -> None:
        self.gen = _load_generator()
        self.committed = json.loads(_REFERENTIAL.read_text(encoding="utf-8"))
        self.catalog = load_catalog()

    def test_committed_file_matches_generator(self) -> None:
        """The on-disk JSON is byte-identical to a fresh generation (no drift)."""
        expected_text = self.gen.render(self.gen.build())
        actual_text = _REFERENTIAL.read_text(encoding="utf-8")
        self.assertEqual(
            actual_text,
            expected_text,
            "referential is stale -- run: python -m scripts.gen_annex_c_referential",
        )

    def test_count_is_124(self) -> None:
        self.assertEqual(self.committed["count"], 124)
        self.assertEqual(len(self.committed["actions"]), 124)

    def test_category_counts(self) -> None:
        """Annex C's twelve categories keep their exact action counts."""
        expected = {
            "Identite / acces": 15,
            "GitHub / DevOps": 14,
            "CRM / Sales": 10,
            "Finance / paiements": 12,
            "Donnees / confidentialite": 11,
            "Slack / communication": 10,
            "Support / customer operations": 10,
            "Cloud / infrastructure": 13,
            "RH": 9,
            "Juridique / conformite": 10,
            "Produit / contenu": 9,
            "MCP / outils": 1,
        }
        actual = dict(Counter(a["category"] for a in self.committed["actions"]))
        self.assertEqual(actual, expected)

    def test_every_row_consistent_with_catalog(self) -> None:
        """Each row points at a real catalog action and copies its posture exactly."""
        for a in self.committed["actions"]:
            spec = self.catalog.get(a["target_system"], a["action_type"])
            self.assertIsNotNone(
                spec, f"{a['target_system']}/{a['action_type']} absent from the catalog"
            )
            assert spec is not None
            self.assertEqual(a["criticality"], spec.criticality.value)
            self.assertEqual(a["risk_level"], spec.risk_level.value)
            self.assertEqual(a["verdict_privileged"], spec.verdict_privileged.value)
            self.assertEqual(a["verdict_default"], spec.verdict_default.value)

    def test_identifiers_unique(self) -> None:
        """No duplicated Annex C dotted type and no duplicated repo (system, action) pair."""
        annex_types = [a["annex_c_action_type"] for a in self.committed["actions"]]
        repo_pairs = [(a["target_system"], a["action_type"]) for a in self.committed["actions"]]
        self.assertEqual(len(annex_types), len(set(annex_types)))
        self.assertEqual(len(repo_pairs), len(set(repo_pairs)))

    def test_repo_action_types_are_snake_case(self) -> None:
        """Repo schema: action_type is a snake_case verb-object, never the dotted Annex form."""
        for a in self.committed["actions"]:
            self.assertNotIn(".", a["action_type"], f"{a['action_type']} still dotted")
            self.assertRegex(a["action_type"], r"^[a-z0-9]+(_[a-z0-9]+)*$")


if __name__ == "__main__":
    unittest.main()
